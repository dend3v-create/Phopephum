export async function action({ request, context }: ActionFunctionArgs) {
  const env = context.cloudflare.env as Env;
  const user = await requireAuth(request, env);
  const today = getThailandTodayDateString();

  const { supabase } = createSupabaseClient(request, env);

  // 1. ตรวจสอบว่าวันนี้เคยจับไพ่ไปหรือยัง
  const { data: plan } = await supabase
    .from("daily_plans")
    .select("daily_card, daily_card_reading")
    .eq("user_id", user.id)
    .eq("date", today)
    .single();

  if (plan && plan.daily_card !== null) {
    const card = TAROT_CARDS[plan.daily_card];
    if (card) {
      return json({
        success: true,
        alreadyPulled: true,
        card,
        reading: plan.daily_card_reading,
        reward: { success: false, earned: 0, message: "รับรางวัลการจับไพ่ไปแล้วในวันนี้" }
      });
    }
  }

  // 2. ถ้ายังไม่เคยจับไพ่ ให้ทำการสุ่มไพ่แบบ Seeded Random (เพื่อไม่ให้เปลี่ยนเมื่อรีเฟรชวันนั้น)
  // หรือใช้สุ่มปกติแล้วเซฟลง DB
  const cardIndex = Math.floor(Math.random() * 22);
  const card = TAROT_CARDS[cardIndex]!;
  
  const readingText = `คำแนะนำสำหรับวันนี้: ${card.meaning} ${card.advice}`;

  // บันทึกผลลงฐานข้อมูล
  const { error: saveError } = await supabase
    .from("daily_plans")
    .upsert({
      user_id: user.id,
      date: today,
      daily_card: cardIndex,
      daily_card_reading: readingText,
    }, { onConflict: "user_id,date" });

  if (saveError) {
    console.error("[daily-card] Save daily card error:", saveError);
    return json({ error: "ไม่สามารถจับไพ่ได้ กรุณาลองใหม่" }, { status: 500 });
  }

  // 3. เคลมรางวัลเหรียญเปิดไพ่ประจำวัน (+1 Soul Ink)
  const rewardResult = await awardCheckinReward(user.id, env);

  return json({
    success: true,
    alreadyPulled: false,
    card,
    reading: readingText,
    reward: rewardResult
  });
}
