export function calculateUserIdentity(birthDate: string, birthTime: string = "12:00"): UserIdentity {
  const lunar = getThaiBaseNumbers(birthDate, birthTime);
  const starNumber = (lunar.dayNum === 8 ? 8 : (lunar.dayNum || 1)) as number;
  const starName = lunar.dayPlanet || "อาทิตย์";

  const data = IDENTITY_REGISTRY[starNumber] || IDENTITY_REGISTRY[1]!;

  return {
    starNumber,
    starName,
    ...data,
  };
}
