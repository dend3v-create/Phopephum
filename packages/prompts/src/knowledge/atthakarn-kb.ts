export interface AtthakarnBirthYamContext {
  day: string;
  dayThai: string;
  period: "day" | "night";
  yamNumber: number;
  subYam: "ton" | "klang" | "plai";
  planet: {
    nameDay: string;
    nameNight: string;
    nameThai: string;
    color: string;
    element: string;
    description: string;
  };
  timeRange: { label: string };
  quality: "good" | "bad" | "neutral";
  subYamQuality: "good" | "bad" | "neutral";
  prediction: {
    generalMeaning: string;
    travel: string;
    lostItems: string;
    sickness: string;
    news: string;
    subYamPredictions: {
      ton: { quality: "good" | "bad" | "neutral"; meaning: string };
      klang: { quality: "good" | "bad" | "neutral"; meaning: string };
      plai: { quality: "good" | "bad" | "neutral"; meaning: string };
    };
  };
  summary: string;
}

