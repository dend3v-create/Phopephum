/**
 * สร้าง Atthakarn Context String สำหรับฉีดเข้า Prompt
 * รับ AtthakarnBirthYamContext (structural type) แทนการ import
 */
export function buildAtthakarnContext(birthYam: AtthakarnBirthYamContext): string {
  const {
    dayThai,
    period,
    yamNumber,
    subYam,
    planet,
    quality,
    prediction,
    subYamQuality,
    summary,
    timeRange,
  } = birthYam;

  const periodThai = period === "day" ? "กลางวัน" : "กลางคืน";
  const planetNameDisplay = period === "day" ? planet.nameDay : planet.nameNight;
  const subYamThai = ({ ton: "ต้น", klang: "กลาง", plai: "ปลาย" } as const)[subYam];
  const qualityLabel = ({ good: "ดี (มงคล)", bad: "ร้าย (ต้องระวัง)", neutral: "ปานกลาง" } as const)[quality];
  const subQualityLabel = ({ good: "ดี", bad: "ร้าย", neutral: "ปานกลาง" } as const)[subYamQuality];

  const planetMeaning = PLANET_BIRTH_YAM_MEANINGS[planetNameDisplay] ??
    `ดาว${planet.nameThai} — ${planet.description}`;

  return `
## ข้อมูลยามเกิด (ยามอัฏฐกาล) — ข้อมูลนี้มีผลต่อชะตาชีวิตโดยตรง

**วันเกิด:** ${dayThai} | **ช่วงเวลา:** ${periodThai}
**ยามเกิด:** ยามที่ ${yamNumber} (${timeRange.label})
**ดาวเจ้ายาม:** ${planetNameDisplay} — ${planet.nameThai} (ธาตุ${planet.element})
**ช่วงยาม:** ยาม${subYamThai} (${subQualityLabel})
**คุณภาพโดยรวม:** ${qualityLabel}

### คำพยากรณ์จากตำรายามอัฏฐกาล
${prediction.generalMeaning}

### ด้านการงานและการเดินทาง
${prediction.travel}

### ด้านข่าวสารและการรับรู้
${prediction.news}

### ด้านสุขภาพ
${prediction.sickness}

### ด้านทรัพย์สินและโชคลาภ
${prediction.lostItems}

### พยากรณ์ยาม${subYamThai} (ช่วงเวลาเกิดที่แน่นอน)
${prediction.subYamPredictions[subYam].meaning}

### ลักษณะและบุคลิกตามดาวเจ้ายาม
${planetMeaning}

---
*สรุปยามเกิด: ${summary}*
`.trim();
}

/**
 * สร้าง Context เวอร์ชันสั้น (สำหรับใส่ใน Prompt หัวข้อหลัก)
 */
export function buildAtthakarnContextShort(birthYam: AtthakarnBirthYamContext): string {
  const { dayThai, period, yamNumber, planet, quality, prediction, timeRange } = birthYam;
  const periodThai = period === "day" ? "กลางวัน" : "กลางคืน";
  const planetNameDisplay = period === "day" ? planet.nameDay : planet.nameNight;
  const qualityLabel = ({ good: "ยามดี (มงคล)", bad: "ยามร้าย", neutral: "ยามปานกลาง" } as const)[quality];
  return `ยามเกิด: ยามที่ ${yamNumber} (${timeRange.label}) ${dayThai} ${periodThai} | เจ้ายาม: ${planetNameDisplay} (${planet.nameThai}) | ${qualityLabel} | ความหมาย: ${prediction.generalMeaning}`;
}
