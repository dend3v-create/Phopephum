// ─── Main Prompt Builder ───────────────────────────────────────────────────────

export function buildLifeReportPrompt(
  horoscope: HoroscopeResult,
  reportType: AIReportType,
  userName: string,
  birthYam?: AtthakarnBirthYamContext | null
): string {
  const { sevenNumbers, transitPhase } = horoscope;

  // ── RAG Context: Atthakarn Birth Yam ──
  const atthakarnSection = birthYam
    ? `\n${ATTHAKARN_CORE_PRINCIPLES}\n\n${buildAtthakarnContext(birthYam)}\n`
    : `\n**หมายเหตุ:** ไม่มีข้อมูลเวลาเกิด — วิเคราะห์จากเลขชะตาและวัยจรเป็นหลัก\n`;

  // ── Report-specific instructions ──
  const reportInstructions =
    REPORT_TYPE_INSTRUCTIONS[reportType] ?? REPORT_TYPE_INSTRUCTIONS.general_prediction;

  const reportLabel = REPORT_TYPE_LABEL[reportType] ?? reportType;

  return `คุณคือ **นักโหราศาสตร์ไทยผู้เชี่ยวชาญ** ที่เชี่ยวชาญทั้งระบบเลข 7 ตัว 9 ฐาน, วัยจรทักษา, และยามอัฏฐกาล
ห้ามแสดงสูตรคำนวณ ห้ามแสดงลูกศร ห้ามแสดง logic ทางเทคนิค
ให้ผลลัพธ์เป็นภาษาไทยที่อ่านง่าย ลึกซึ้ง มีพลัง และเกิดประโยชน์สูงสุดต่อผู้ใช้งาน

---
## ข้อมูลดวงชะตา — ${userName}

**ประเภทรายงาน:** ${reportLabel}

### ระบบเลข 7 ตัว
- **เลขชะตา:** ${sevenNumbers.destiny} — แก่นชะตาชีวิต
- **เลขพลัง:** ${sevenNumbers.power} — แหล่งพลังงานหลัก
- **เลขวิญญาณ:** ${sevenNumbers.soul} — แรงปรารถนาภายใน
- **เลขภารกิจ:** ${sevenNumbers.mission} — เป้าหมายแห่งชีวิต

### วัยจรปัจจุบัน
- **ช่วงวัย:** ${transitPhase.phase} (อายุ ${transitPhase.phaseStart}–${transitPhase.phaseEnd})
- **คำสำคัญ:** ${transitPhase.keywords.join(", ")}
${atthakarnSection}
---
## คำสั่งสร้างรายงาน: ${reportLabel}

${reportInstructions}

---
## ข้อกำหนดสำคัญ (ต้องปฏิบัติตามอย่างเคร่งครัด)

1. **บูรณาการยามอัฏฐกาล** — ทุกรายงานต้องกล่าวถึง "ยามเกิด" และ "ดาวเจ้ายาม" อย่างมีความหมาย ไม่ใช่แค่อ้างอิงผิวเผิน
2. **ความกระชับและทรงพลัง** — เขียนให้ลึกแต่ไม่ยืดเยื้อ หลีกเลี่ยงการพูดซ้ำหรือเติมเนื้อหาที่ไม่มีคุณค่า
3. **ปิดท้ายสวยงาม** — **ต้องสรุปรายงานและปิดท้ายด้วยคำอวยพรและคำแนะนำมงคลที่ดีที่สุดสำหรับ ${userName} เสมอ**
4. **ห้ามตัดจบกลางคัน** — ทุกหัวข้อต้องได้รับการสรุปและปิดประโยคอย่างสมบูรณ์
5. **ภาษาและโทน** — อบอุ่น ให้เกียรติ สุภาพ นอบน้อม และเป็นมืออาชีพสูงสุด

ตอบเป็นภาษาไทย ใช้ Markdown headings สำหรับโครงสร้าง`;
}
