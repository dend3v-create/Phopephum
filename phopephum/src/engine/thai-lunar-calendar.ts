// ─────────────────────────────────────────────────────────────────────────────
// Core: แปลง Gregorian → เดือนไทย โดยใช้ lookup table
// ─────────────────────────────────────────────────────────────────────────────

/**
 * แปลง Gregorian date → เดือนไทย (จันทรคติ)
 * ใช้ lookup table เป็นหลัก, fallback เป็น Suriyayat algorithm
 */
export function gregorianToThaiLunar(date: Date): ThaiLunarResult {
  const ceYear = date.getFullYear();
  const dateMs = date.getTime();

  // หา entries ที่ ceYear ตรงกันใน lookup table
  const yearEntries: Array<{ month: number; startMs: number }> = [];

  for (let m = 1; m <= 13; m++) {
    const key = `${ceYear}-${m}`;
    if (THAI_LUNAR_NEW_MONTH[key]) {
      const startDate = new Date(THAI_LUNAR_NEW_MONTH[key] + "T00:00:00");
      yearEntries.push({ month: m, startMs: startDate.getTime() });
    }
  }

  // ยังต้องดู entries ของปีก่อน (เดือน 10-12 อาจ overlap)
  for (let m = 8; m <= 13; m++) {
    const key = `${ceYear - 1}-${m}`;
    if (THAI_LUNAR_NEW_MONTH[key]) {
      const startDate = new Date(THAI_LUNAR_NEW_MONTH[key] + "T00:00:00");
      if (startDate.getTime() < dateMs) {
        yearEntries.push({ month: m, startMs: startDate.getTime() });
      }
    }
  }

  if (yearEntries.length > 0) {
    // เรียงตาม startMs
    yearEntries.sort((a, b) => a.startMs - b.startMs);

    // หา entry ที่ date อยู่ใน range
    let currentMonth = yearEntries[0];
    for (const entry of yearEntries) {
      if (entry.startMs <= dateMs) {
        currentMonth = entry;
      } else {
        break;
      }
    }

    const daysIn = Math.floor((dateMs - currentMonth.startMs) / 86400000);
    const isWaxing = daysIn < 15;
    const lunarDay = isWaxing ? daysIn + 1 : daysIn - 14;

    return {
      month: currentMonth.month,
      isWaxing,
      lunarDay,
      monthNumber: currentMonth.month > 7 ? currentMonth.month - 7 : currentMonth.month,
      monthNameThai: THAI_MONTH_NAMES[currentMonth.month] ?? String(currentMonth.month),
      isApproximate: false,
    };
  }

  // Fallback: ใช้ Suriyayat approximation (ดีกว่า approximateThaiMonth เดิม)
  return suriyayatApproximation(date);
}

/**
 * Suriyayat approximation — ใช้เมื่อไม่มีข้อมูลใน lookup table
 * ดีกว่า approximateThaiMonth เดิมที่ off-by-2 เดือน
 */
function suriyayatApproximation(date: Date): ThaiLunarResult {
  const ceYear = date.getFullYear();
  const ceMonth = date.getMonth() + 1; // 1-12
  const ceDay = date.getDate();

  // Thai lunar month เปลี่ยนเร็วกว่า Gregorian ~11 วัน/ปี
  // เดือน 1 ไทย (อ้าย) เริ่มช่วง ธ.ค.–ม.ค.
  // offset จาก Gregorian ≈ +2 เดือน (โดยเฉลี่ย ±1)
  
  // คำนวณ approximate Thai month:
  // เดือนไทย ≈ ((Gregorian month + 1) % 12) + 1
  // แต่ต้องปรับตาม day ด้วย
  
  let thaiMonth: number;
  
  // Gregorian to Thai lunar month mapping (approximate, ±1 month)
  // Based on average offset over 100 years
  const offset = ceDay >= 20 ? 2 : 1; // ปลายเดือน offset มากกว่า
  thaiMonth = ceMonth + offset;
  if (thaiMonth > 12) thaiMonth -= 12;
  
  const monthNumber = thaiMonth > 7 ? thaiMonth - 7 : thaiMonth;

  return {
    month: thaiMonth,
    isWaxing: true,
    lunarDay: 1,
    monthNumber,
    monthNameThai: THAI_MONTH_NAMES[thaiMonth] ?? String(thaiMonth),
    isApproximate: true,
  };
}

/**
 * ฟังก์ชัน helper สำหรับ seven-numbers.ts
 * ใช้แทน approximateThaiMonth เดิม
 */
export function getThaiMonthNumber(date: Date): number {
  const result = gregorianToThaiLunar(date);
  return result.monthNumber;
}

export function getThaiMonthFull(date: Date): { month: number; monthNumber: number; isApproximate: boolean } {
  const result = gregorianToThaiLunar(date);
  return {
    month: result.month,
    monthNumber: result.monthNumber,
    isApproximate: result.isApproximate,
  };
}
