/**
 * calculatePower.ts
 * คำนวณกำลังดวง (Power Score) — ฐานกำลังดาวพระเคราะห์
 */

/**
 * ผลรวมกำลังรวม (raw sum)
 */
export function calculatePower(values: number[]): number {
  return values.reduce((sum, val) => sum + val, 0)
}

/**
 * คำนวณ "ฐานกำลัง" จาก row4 ของ เลข 7 ตัว 9 ฐาน
 * ฐานกำลัง 15 = เสน่ห์มหานิยม
 * ฐานกำลัง 16 = โชคลาภ เทวดาหนุน
 * ฐานกำลัง 17 = เจรจาเก่ง ค้าขายเก่ง
 * ฐานกำลัง 18 = ความยิ่งใหญ่ พลังผู้นำ
 * ฐานกำลัง 19 = มหาเสน่ห์ มีบุญบารมี
 * ฐานกำลัง 20 = ความอดทนสูง
 * ฐานกำลัง 21 = ความสุขสมหวัง
 */
export const POWER_MEANINGS: Record<number, { title: string; description: string }> = {
  13: { title: 'ฐานปานกลาง',       description: 'มีพลังปานกลาง เส้นทางราบเรียบ ต้องสร้างเองทีละก้าว' },
  14: { title: 'ฐานเสริมความรู้',    description: 'ความรู้และปัญญาคือทรัพย์สินที่ยิ่งใหญ่ที่สุด' },
  15: { title: 'เสน่ห์มหานิยม',      description: 'ผู้คนรักและชื่นชม มีเสน่ห์ดึงดูดโดยธรรมชาติ' },
  16: { title: 'โชคลาภ เทวดาหนุน',   description: 'มีสิ่งศักดิ์สิทธิ์คุ้มครอง โชคดีในจังหวะสำคัญ' },
  17: { title: 'เจรจาเก่ง ค้าขายเก่ง', description: 'พูดได้ทุกเรื่อง ขายได้ทุกอย่าง มีพรสวรรค์ด้านธุรกิจ' },
  18: { title: 'ความยิ่งใหญ่ พลังผู้นำ', description: 'เกิดมาเพื่อเป็นผู้นำ มีพลังบารมีปกครองผู้คน' },
  19: { title: 'มหาเสน่ห์ มีบุญบารมี',  description: 'บุญบารมีเต็มเปี่ยม คนยอมรับโดยไม่ต้องพิสูจน์' },
  20: { title: 'ความอดทนสูง',          description: 'ยิ่งผ่านความยากยิ่งแข็งแกร่ง ความอดทนคือชัยชนะ' },
  21: { title: 'ความสุขสมหวัง',         description: 'ชีวิตสมปรารถนา ความสุขที่แท้จริงในบั้นปลาย' },
}

export function getPowerMeaning(power: number): string {
  const entry = POWER_MEANINGS[power]
  if (entry) return `${entry.title} — ${entry.description}`
  if (power < 13) return 'กำลังต้องสร้างใหม่ — นี่คือจุดเริ่มต้นของการเติบโต'
  if (power > 21) return 'กำลังพิเศษสูงสุด — พลังงานล้นเหลือ ต้องบริหารอย่างชาญฉลาด'
  return 'กำลังปานกลาง — เส้นทางของตัวเองที่สร้างขึ้นด้วยความมุ่งมั่น'
}
